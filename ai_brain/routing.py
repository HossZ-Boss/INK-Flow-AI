class _RoutingLLMOutput(BaseModel):
    """Subset response generated by the routing LLM call."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    confidence_level: ConfidenceLevel = Field(
        description="Routing confidence: high, medium, or low.",
    )
    ai_reasoning: str = Field(
        description="Brief explanation for routing and risk decisions.",
    )


class _DraftReplyLLMOutput(BaseModel):
    """Strict client-facing reply returned by the language model."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    draft_reply: StrictStr = Field(min_length=1, max_length=2000)


class _ArtistRoutingDecision(BaseModel):
    """Validated artist result produced before risk and reply generation."""

    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)

    suggested_artist: SuggestedArtist
    confidence_level: ConfidenceLevel
    reasoning: str = Field(min_length=1, max_length=500)


class TattooRouter:
    """Apply routing and risk rules, then craft a staff-ready draft reply."""

    def __init__(
        self,
        llm: ChatOpenAI | None = None,
        model_name: str | None = None,
        reply_composer: ConversationReplyComposer | None = None,
        artist_config_manager: ArtistConfigManager | None = None,
        vector_store: VectorStoreManager | None = None,
        routing_rule_engine: RoutingRuleEngine | None = None,
    ) -> None:
        """Initialize model, configuration, retrieval, and safety services."""
        self._llm = llm or get_chat_model(model_name=model_name)
        self._parser = JsonOutputParser(pydantic_object=_RoutingLLMOutput)
        self._draft_parser = JsonOutputParser(
            pydantic_object=_DraftReplyLLMOutput
        )
        self._reply_composer = reply_composer or ConversationReplyComposer()
        self._artist_config = (
            artist_config_manager
            if artist_config_manager is not None
            else ArtistConfigManager()
        )
        self._vector_store = vector_store
        self._routing_rule_engine = (
            routing_rule_engine
            if routing_rule_engine is not None
            else RoutingRuleEngine()
        )

    @property
    def chat_model(self) -> ChatOpenAI:
        """Return the chat model shared with other studio-facing services."""
        return self._llm

    def route(
        self,
        extracted: TattooExtractionDraft,
        current_message: str = "",
        recent_chat_history: list[Message] | None = None,
        existing_db_state: dict[str, Any] | None = None,
        message_source: MessageSource = "whatsapp",
    ) -> AIExtractionOutput:
        """Create final output with reply formatting for its source."""
        history = recent_chat_history or []
        db_state = existing_db_state or {}
        artist_decision = self._suggest_artist(extracted)
        risk_level = self._classify_risk(extracted)
        pending_review_reasons = self._review_reasons(
            extracted,
            artist_decision,
            current_message,
        )
        immediate_review = self._requires_immediate_staff_review(
            pending_review_reasons
        )
        staff_review_required = risk_level == "high" or immediate_review
        review_reasons = (
            pending_review_reasons if staff_review_required else []
        )
        if extracted.conversation_status == "closed":
            intake_status = "closed"
        elif staff_review_required:
            intake_status = "needs_staff_review"
        elif extracted.missing_information:
            intake_status = "collecting_info"
        else:
            intake_status = "ready_for_review"

        if extracted.conversation_status == "closed":
            llm_output = _RoutingLLMOutput(
                confidence_level="high",
                ai_reasoning="The client withdrew from the inquiry.",
            )
        elif immediate_review:
            llm_output = _RoutingLLMOutput(
                confidence_level="low",
                ai_reasoning=(
                    "The request is paused for deterministic staff review."
                ),
            )
        else:
            llm_output = self._routing_llm_output(
                artist_decision=artist_decision,
                extracted=extracted,
                risk_level=risk_level,
                current_message=current_message,
                recent_chat_history=history,
            )
        ai_reasoning = self._combine_routing_reasoning(
            artist_decision.reasoning,
            llm_output.ai_reasoning,
        )
        draft_reply = self._generate_draft_reply(
            extracted=extracted,
            current_message=current_message,
            recent_chat_history=history,
            suggested_artist=artist_decision.suggested_artist,
            risk_level=risk_level,
            existing_db_state=db_state,
            message_source=message_source,
            review_reasons=review_reasons,
        )

        auto_reply_allowed = (
            risk_level == "low" and not staff_review_required
        )

        return AIExtractionOutput(
            client_name=extracted.client_name,
            tattoo_idea=extracted.tattoo_idea,
            style_tags=extracted.style_tags,
            placement=extracted.placement,
            size_estimate_cm=extracted.size_estimate_cm,
            color_preference=extracted.color_preference,
            date=extracted.date,
            time=extracted.time,
            preferred_artist=extracted.preferred_artist,
            appointment_type=extracted.appointment_type,
            availability=extracted.availability,
            tattoo_project_type=extracted.tattoo_project_type,
            party_size=extracted.party_size,
            multi_entity_detected=extracted.multi_entity_detected,
            complexity_notes=extracted.complexity_notes,
            size_description=extracted.size_description,
            size_status=extracted.size_status,
            artist_preference_mode=extracted.artist_preference_mode,
            pricing_requested=extracted.pricing_requested,
            client_intent=extracted.client_intent,
            conversation_status=extracted.conversation_status,
            intake_status=intake_status,
            staff_review_required=staff_review_required,
            review_reasons=review_reasons,
            suggested_artist=artist_decision.suggested_artist,
            confidence_level=artist_decision.confidence_level,
            ai_reasoning=ai_reasoning,
            missing_information=extracted.missing_information,
            risk_level=risk_level,
            draft_reply=draft_reply,
            auto_reply_allowed=auto_reply_allowed,
            auto_reply=(
                message_source in {"outlook", "whatsapp"}
                and auto_reply_allowed
            ),
            telegram_review_required=staff_review_required,
        )

    def _generate_draft_reply(
        self,
        extracted: TattooExtractionDraft,
        current_message: str,
        recent_chat_history: list[Message],
        suggested_artist: SuggestedArtist,
        risk_level: RiskLevel,
        existing_db_state: dict[str, Any],
        message_source: MessageSource,
        review_reasons: list[str],
    ) -> str:
        """Generate a draft and apply channel-specific finishing rules."""
        reply = self._compose_draft_reply(
            extracted=extracted,
            current_message=current_message,
            recent_chat_history=recent_chat_history,
            suggested_artist=suggested_artist,
            risk_level=risk_level,
            existing_db_state=existing_db_state,
            message_source=message_source,
            review_reasons=review_reasons,
        )
        if (
            message_source != "whatsapp"
            or extracted.conversation_status == "closed"
            or any(message.role == "assistant" for message in recent_chat_history)
        ):
            return reply
        return self._with_whatsapp_welcome(
            reply,
            self._client_first_name(extracted, existing_db_state),
        )

    def _with_whatsapp_welcome(self, reply: str, first_name: str) -> str:
        """Open the first WhatsApp reply with a studio welcome."""
        opening = reply[:120].casefold()
        if "welcome" in opening and _STUDIO_NAME.casefold() in opening:
            return reply
        body = _LEADING_GREETING_PATTERN.sub("", reply.strip(), count=1)
        if body:
            body = body[0].upper() + body[1:]
        greeting = f"Hi {first_name}" if first_name else "Hi"
        welcome = f"{greeting}, welcome to {_STUDIO_NAME}!"
        return f"{welcome} {body}".strip()

    def _client_first_name(
        self,
        extracted: TattooExtractionDraft,
        existing_db_state: dict[str, Any],
    ) -> str:
        """Return a usable first name from extraction or backend state."""
        candidates: list[object] = [extracted.client_name]
        for record in (
            existing_db_state.get("lead"),
            existing_db_state.get("intake"),
            existing_db_state,
        ):
            if isinstance(record, dict):
                candidates.extend(
                    record.get(key) for key in ("client_name", "name")
                )
        for candidate in candidates:
            if isinstance(candidate, str) and candidate.strip():
                first = candidate.split()[0].strip(",.")
                if first.isalpha():
                    return first.capitalize()
        return ""

    def _compose_draft_reply(
        self,
        extracted: TattooExtractionDraft,
        current_message: str,
        recent_chat_history: list[Message],
        suggested_artist: SuggestedArtist,
        risk_level: RiskLevel,
        existing_db_state: dict[str, Any],
        message_source: MessageSource,
        review_reasons: list[str],
    ) -> str:
        """Generate and strictly validate a client-facing draft reply."""
        suggested_artist_details = self._artist_profile_summary(
            suggested_artist
        )
        artist_directory = self._artist_directory_summary()
        if extracted.conversation_status == "closed":
            return self._reply_composer.compose_closed(
                message_source=message_source,
                existing_db_state=existing_db_state,
                client_name=extracted.client_name,
            )

        if self._requires_immediate_staff_review(review_reasons):
            return self._reply_composer.compose_staff_review(
                extracted=extracted,
                current_message=current_message,
                message_source=message_source,
                existing_db_state=existing_db_state,
                review_reasons=review_reasons,
            )

        if message_source == "outlook":
            fallback_draft = self._reply_composer.compose_outlook_email(
                extracted=extracted,
                existing_db_state=existing_db_state,
                current_message=current_message,
                recent_chat_history=recent_chat_history,
                suggested_artist=suggested_artist,
                suggested_artist_details=suggested_artist_details,
                artist_directory=artist_directory,
            )
        else:
            fallback_draft = self._reply_composer.compose_validation(
                extracted=extracted,
                current_message=current_message,
                recent_chat_history=recent_chat_history,
                risk_level=risk_level,
                suggested_artist=suggested_artist,
                suggested_artist_details=suggested_artist_details,
                artist_directory=artist_directory,
            )

        try:
            format_instructions = self._draft_parser.get_format_instructions()
            human_prompt = build_draft_reply_human_prompt(
                current_message=current_message,
                extracted_details={
                    "tattoo_idea": extracted.tattoo_idea,
                    "style": list(extracted.style_tags),
                    "placement": extracted.placement,
                    "size": extracted.size_estimate_cm,
                    "color": extracted.color_preference,
                    "date": extracted.date,
                    "time": extracted.time,
                    "preferred_artist": extracted.preferred_artist,
                    "appointment_type": extracted.appointment_type,
                    "availability": extracted.availability,
                    "tattoo_project_type": extracted.tattoo_project_type,
                    "party_size": extracted.party_size,
                    "multi_entity_detected": (
                        extracted.multi_entity_detected
                    ),
                    "complexity_notes": extracted.complexity_notes,
                    "projects": [
                        project.model_dump(mode="json")
                        for project in extracted.projects
                    ],
                    "size_description": extracted.size_description,
                    "size_status": extracted.size_status,
                    "artist_preference_mode": (
                        extracted.artist_preference_mode
                    ),
                    "pricing_requested": extracted.pricing_requested,
                    "client_intent": extracted.client_intent,
                    "conversation_status": extracted.conversation_status,
                    "specialised_placement_review": (
                        specialised_placement_requires_review(
                            extracted.placement
                        )
                    ),
                    "suggested_artist_profile": suggested_artist_details,
                    "artist_directory": artist_directory,
                    "date_confirmation_question": (
                        date_confirmation_question(extracted.date_to_confirm)
                        if extracted.date_to_confirm
                        else ""
                    ),
                },
                missing_information=extracted.missing_information,
                recent_chat_history=recent_chat_history,
                suggested_artist=suggested_artist,
                risk_level=risk_level,
                format_instructions=format_instructions,
                existing_db_state=existing_db_state,
                message_source=message_source,
                safe_fallback_draft=fallback_draft,
            )
            response = self._llm.invoke(
                [
                    SystemMessage(content=DRAFT_REPLY_SYSTEM_PROMPT),
                    HumanMessage(content=human_prompt),
                ]
            )
            parsed = self._draft_parser.parse(
                self._coerce_content_to_text(response.content)
            )
            output = _DraftReplyLLMOutput.model_validate(parsed)
            return self._validate_draft_reply(
                draft_reply=output.draft_reply,
                extracted=extracted,
                message_source=message_source,
                current_message=current_message,
            )
        except Exception as exc:  # pragma: no cover - defensive branch
            record_llm_failure(exc)
            LOGGER.warning(
                "Draft reply LLM fallback used: %s [%s]",
                exc,
                llm_failure_context(exc),
            )
            return fallback_draft

    def _validate_draft_reply(
        self,
        draft_reply: str,
        extracted: TattooExtractionDraft,
        message_source: MessageSource,
        current_message: str,
    ) -> str:
        """Reject malformed or unsafe model prose and trigger safe fallback."""
        reply = draft_reply.strip()
        normalized = " ".join(reply.casefold().split())
        if reply.count("?") > 2:
            raise ValueError("Draft reply contains too many questions.")
        if any(
            phrase in normalized
            for phrase in (
                "not sure tattoo",
                "unknown tattoo",
                "studio_visit",
                "we have recorded the following details",
            )
        ):
            raise ValueError("Draft reply exposes invalid or robotic wording.")
        if _ARTIST_SIZE_DELEGATION_PATTERN.search(reply):
            raise ValueError("Draft reply delegates size selection to an artist.")
        if extracted.conversation_status == "closed" and "?" in reply:
            raise ValueError("Closed inquiries cannot contain questions.")
        if extracted.date_to_confirm:
            pending = date.fromisoformat(extracted.date_to_confirm)
            if not re.search(
                rf"\b{pending.day}(?:st|nd|rd|th)?\s+{pending:%B}\b"
                rf"|\b{pending:%B}\s+{pending.day}\b",
                reply,
                flags=re.IGNORECASE,
            ) or "?" not in reply:
                raise ValueError(
                    "Draft must ask the client to confirm the exact date."
                )
        mentioned_artists = [
            artist
            for artist in ARTIST_PREFERENCE_OPTIONS
            if re.search(rf"\b{artist.casefold()}\b", normalized)
        ]
        if (
            self._is_artist_roster_question(current_message)
            and not ARTIST_CHOICE_HELP_PATTERN.search(current_message)
        ):
            missing_artists = [
                artist
                for artist in ARTIST_PREFERENCE_OPTIONS
                if artist not in mentioned_artists
            ]
            if missing_artists:
                raise ValueError(
                    "Artist-roster reply omitted: "
                    + ", ".join(missing_artists)
                )
        if (
            self._is_artist_roster_question(current_message)
            and len(mentioned_artists) >= 4
            and reply.count("\n") < 3
        ):
            raise ValueError("Artist list must put each artist on its own line.")
        if (
            extracted.missing_information
            and extracted.conversation_status != "closed"
            and "?" not in reply
        ):
            raise ValueError(
                "Draft reply omits a question while intake details are missing."
            )
        if (
            not extracted.missing_information
            and not self._mentions_confirmed_intake_detail(reply, extracted)
        ):
            raise ValueError(
                "Completed-intake draft does not confirm any client details."
            )
        if (
            len(extracted.missing_information) != 1
            and extracted.conversation_status != "closed"
            and self._restated_detail_count(
                reply,
                extracted,
                current_message,
                count_styles=not self._is_artist_roster_question(
                    current_message
                ),
            )
            >= 3
        ):
            raise ValueError(
                "Draft restates the collected details outside the final-item "
                "turn."
            )
        repeated_fields = self._questions_for_completed_fields(reply, extracted)
        if repeated_fields:
            raise ValueError(
                "Draft asks for completed fields: "
                + ", ".join(repeated_fields)
            )
        if message_source == "whatsapp":
            limit = (
                _WHATSAPP_MAX_DIRECTORY_REPLY_CHARS
                if self._is_artist_roster_question(current_message)
                else _WHATSAPP_MAX_REPLY_CHARS
            )
            if len(reply) > limit:
                raise ValueError(
                    f"WhatsApp draft exceeds {limit} characters."
                )
            if re.match(r"^dear\b", reply, flags=re.IGNORECASE) or (
                "kind regards" in normalized
            ):
                raise ValueError("WhatsApp draft uses email formatting.")
        if message_source == "outlook":
            if reply.casefold().startswith("subject:"):
                raise ValueError("Outlook draft must not include a subject.")
            if not re.match(r"^Dear\s+[^,\n]+,", reply):
                raise ValueError("Outlook draft is missing its salutation.")
            if "kind regards" not in normalized:
                raise ValueError("Outlook draft is missing its sign-off.")
            if "tattoo hysteria" not in normalized:
                raise ValueError("Outlook draft is missing the studio name.")
        return reply

    def _restated_detail_count(
        self,
        draft_reply: str,
        extracted: TattooExtractionDraft,
        current_message: str = "",
        count_styles: bool = True,
    ) -> int:
        """Count earlier-collected fields that a draft repeats back.

        Details the client stated in the current message do not count, so a
        reply can still acknowledge what was just said.
        """

        def normalize(text: str) -> str:
            return " ".join(
                re.sub(r"[\u2013\u2014-]", " ", text.casefold()).split()
            )

        reply = normalize(draft_reply)
        message = normalize(current_message)

        def recapped(pattern: str) -> bool:
            return bool(
                re.search(pattern, reply) and not re.search(pattern, message)
            )

        def phrase(value: str) -> str:
            normalized = normalize(value)
            if len(normalized) < 3:
                return ""
            return rf"\b{re.escape(normalized)}\b"

        patterns: list[str] = []
        patterns.append(phrase(extracted.placement))
        size_numbers = re.findall(r"\d+(?:\.\d+)?", extracted.size_estimate_cm)
        if size_numbers:
            patterns.append(
                "".join(
                    rf"(?=.*\b{re.escape(number)}\b)" for number in size_numbers
                )
            )
        if extracted.color_preference == "black-and-grey":
            patterns.append(r"\bblack (?:and|&) gr[ae]y\b")
        elif extracted.color_preference == "color":
            patterns.append(r"\b(?:full )?colou?r(?:ed|ful)?\b")
        if count_styles:
            style_patterns = [
                phrase(style)
                for style in extracted.style_tags
                if style not in {"unknown", "black-and-grey"}
            ]
            style_patterns = [pattern for pattern in style_patterns if pattern]
            if style_patterns:
                patterns.append("|".join(style_patterns))
        patterns.append(phrase(extracted.tattoo_idea))
        if extracted.preferred_artist not in {"", "No preference"}:
            patterns.append(phrase(extracted.preferred_artist))
        if extracted.appointment_type:
            patterns.append(phrase(extracted.appointment_type.replace("_", " ")))
        return sum(1 for pattern in patterns if pattern and recapped(pattern))

    def _mentions_confirmed_intake_detail(
        self,
        draft_reply: str,
        extracted: TattooExtractionDraft,
    ) -> bool:
        """Require completed-intake replies to reflect known client context."""
        normalized_reply = " ".join(draft_reply.casefold().split())
        values = (
            extracted.tattoo_idea,
            extracted.placement,
            extracted.size_estimate_cm,
            extracted.date,
            extracted.time,
            extracted.preferred_artist,
            extracted.appointment_type.replace("_", " "),
            extracted.tattoo_project_type,
        )
        meaningful_values = [
            " ".join(value.casefold().split())
            for value in values
            if value and len(" ".join(value.split())) >= 3
        ]
        style_values = [
            style.casefold()
            for style in extracted.style_tags
            if style != "unknown"
        ]
        return any(
            value in normalized_reply
            for value in [*meaningful_values, *style_values]
        )

    def _questions_for_completed_fields(
        self,
        draft_reply: str,
        extracted: TattooExtractionDraft,
    ) -> list[str]:
        """Identify questions that request information already in state."""
        question_text = " ".join(
            re.findall(r"[^.!?\n]{1,300}\?", draft_reply.casefold())
        )
        if not question_text:
            return []
        missing = set(extracted.missing_information)
        repeated: list[str] = []
        for field_name, markers in _DRAFT_QUESTION_MARKERS.items():
            if field_name in missing:
                continue
            if field_name == "size in cm" and extracted.size_status == "approximate":
                continue
            if any(marker in question_text for marker in markers):
                repeated.append(field_name)
        return repeated

    def _artist_profile_summary(
        self,
        suggested_artist: SuggestedArtist,
    ) -> str:
        """Return client-safe portfolio context for a suggested artist."""
        requested_name = self._canonical_artist_name(suggested_artist)
        for artist in self._artist_config.get_active_artists():
            configured_name = self._canonical_artist_name(
                artist.display_name
            )
            if configured_name == requested_name:
                if not artist.portfolio_handles:
                    return artist.profile_summary
                portfolios = self._natural_list(artist.portfolio_handles)
                return (
                    f"{artist.profile_summary} Portfolio: {portfolios}."
                )
        return ""

    def _canonical_artist_name(self, value: str) -> str:
        """Normalize legacy artist display names for compatibility."""
        normalized = value.strip().casefold()
        return _ARTIST_DISPLAY_ALIASES.get(normalized, normalized)

    def _artist_directory_summary(self) -> str:
        """Return a concise client-safe directory from configured profiles."""
        profiles = {
            artist.display_name.casefold(): artist
            for artist in self._artist_config.get_active_artists()
        }
        descriptions: list[str] = []
        for display_name in ARTIST_PREFERENCE_OPTIONS:
            profile = profiles.get(display_name.casefold())
            if profile is None:
                continue
            specialties = ", ".join(profile.specialties)
            descriptions.append(f"• {display_name}: {specialties}")
        if not descriptions:
            return ""
        return "Here are our resident artists:\n" + "\n".join(descriptions)

    def _natural_list(self, values: list[str]) -> str:
        """Join client-facing values with natural punctuation."""
        if len(values) == 1:
            return values[0]
        if len(values) == 2:
            return f"{values[0]} and {values[1]}"
        return f"{', '.join(values[:-1])}, and {values[-1]}"

    def _is_artist_roster_question(self, message: str) -> bool:
        """Return whether the client requested the studio artist directory."""
        return bool(ARTIST_ROSTER_PATTERN.search(message))

    def _suggest_artist(
        self,
        extracted: TattooExtractionDraft,
    ) -> _ArtistRoutingDecision:
        """Select an artist from configured rules or history."""
        if specialised_placement_requires_review(extracted.placement):
            return _ArtistRoutingDecision(
                suggested_artist="Unclear",
                confidence_level="low",
                reasoning=(
                    "Studio approval is required for this specialised "
                    "placement before an artist can be recommended."
                ),
            )
        explicit = self._explicit_artist_decision(extracted)
        if explicit is not None:
            return explicit

        rules = self._routing_rule_engine.evaluate(extracted)
        matches = self._search_similar_cases(extracted)
        rule_decision = self._suggest_from_rules(
            rules=rules,
            matches=matches,
            extracted=extracted,
        )
        if rule_decision is not None:
            return rule_decision
        if matches:
            return self._suggest_from_history(matches, extracted)
        return self._suggest_from_config(extracted)

    def _explicit_artist_decision(
        self,
        extracted: TattooExtractionDraft,
    ) -> _ArtistRoutingDecision | None:
        """Honor an active artist explicitly selected by the client."""
        preferred = extracted.preferred_artist
        if not preferred or preferred == "No preference":
            return None
        profile = next(
            (
                artist
                for artist in self._artist_config.get_active_artists()
                if self._canonical_artist_name(artist.display_name)
                == self._canonical_artist_name(preferred)
            ),
            None,
        )
        if profile is None:
            return None
        return _ArtistRoutingDecision(
            suggested_artist=profile.display_name,
            confidence_level="high",
            reasoning=(
                f"Suggested artist: {profile.display_name} because the client "
                "explicitly requested this active artist."
            ),
        )

    def _search_similar_cases(
        self,
        extracted: TattooExtractionDraft,
    ) -> list[tuple[float, DecisionHistoryExample]]:
        """Retrieve similar staff-verified cases from the learning index."""
        if self._vector_store is None:
            return []
        try:
            return self._vector_store.search_similar_cases(
                self._build_vector_query(extracted),
                top_k=_VECTOR_SEARCH_TOP_K,
            )
        except Exception as exc:  # pragma: no cover - defensive branch
            LOGGER.warning("Artist vector search failed: %s", exc)
            return []

    def _build_vector_query(self, extracted: TattooExtractionDraft) -> str:
        """Render current features in the vector store's indexed format."""
        styles = ", ".join(extracted.style_tags) or "unknown"
        placement = extracted.placement or "unknown"
        size = extracted.size_estimate_cm or "unknown"
        color = extracted.color_preference or "unknown"
        return (
            f"Tattoo styles: {styles}. Placement: {placement}. "
            f"Size in centimeters: {size}. Color preference: {color}."
        )

    def _suggest_from_history(
        self,
        matches: list[tuple[float, DecisionHistoryExample]],
        extracted: TattooExtractionDraft,
    ) -> _ArtistRoutingDecision:
        """Choose the most frequent eligible artist in similar cases."""
        assignments: Counter[str] = Counter()
        seen_example_ids: set[str] = set()
        size_cm = parse_size_cm(extracted.size_estimate_cm)
        for _, example in matches:
            if example.example_id in seen_example_ids:
                continue
            seen_example_ids.add(example.example_id)
            artist_key = example.final_artist_key
            if (
                artist_key is not None
                and self._artist_config.validate_artist_assignment(
                    artist_key,
                    extracted.style_tags,
                )
            ):
                profile = self._artist_config.get_artist_by_key(artist_key)
                if (
                    profile is not None
                    and self._artist_accepts_size(profile, size_cm)
                ):
                    assignments[artist_key] += 1

        if not assignments:
            return self._manual_history_decision(
                "Similar cases contain no active artist assignments "
                "compatible with the detected style and size."
            )

        best_count = max(assignments.values())
        winners = [
            artist_key
            for artist_key, count in assignments.items()
            if count == best_count
        ]
        if len(winners) != 1:
            return self._manual_history_decision(
                "Similar cases produced an unresolved artist tie."
            )

        profile = self._artist_config.get_artist_by_key(winners[0])
        if profile is None or not profile.is_active:
            return self._manual_history_decision(
                "The historical artist is unavailable for assignment."
            )
        confidence: ConfidenceLevel = "medium"
        if best_count >= 2:
            confidence = "high"
        return _ArtistRoutingDecision(
            suggested_artist=profile.display_name,
            confidence_level=confidence,
            reasoning=(
                f"Suggested artist: {profile.display_name} based on "
                f"{best_count} similar historical cases."
            ),
        )

    def _manual_history_decision(
        self,
        reason: str,
    ) -> _ArtistRoutingDecision:
        """Return a safe unresolved result for unusable history."""
        return _ArtistRoutingDecision(
            suggested_artist="Unclear",
            confidence_level="low",
            reasoning=f"Manual artist assignment required. {reason}",
        )

    def _suggest_from_rules(
        self,
        rules: list[RoutingRule],
        matches: list[tuple[float, DecisionHistoryExample]],
        extracted: TattooExtractionDraft,
    ) -> _ArtistRoutingDecision | None:
        """Apply the highest-priority valid rule and add history support."""
        valid_rules = self._valid_artist_rules(rules, extracted)
        if not valid_rules:
            return None

        highest_priority = valid_rules[0].priority
        highest_rules = [
            rule for rule in valid_rules if rule.priority == highest_priority
        ]
        artist_keys = {rule.artist_key for rule in highest_rules}
        rule_names = self._rule_names(valid_rules)
        if len(artist_keys) != 1:
            return _ArtistRoutingDecision(
                suggested_artist="Unclear",
                confidence_level="low",
                reasoning=(
                    "Manual artist assignment required. Conflicting "
                    f"highest-priority rules matched. Applied routing rules: "
                    f"{rule_names}."
                ),
            )

        artist_key = next(iter(artist_keys))
        profile = self._artist_config.get_artist_by_key(artist_key)
        if profile is None or not profile.is_active:
            return None

        support_count = self._historical_artist_support(
            artist_key,
            matches,
        )
        confidence: ConfidenceLevel = "medium"
        if support_count >= 2:
            confidence = "high"
        reasoning = (
            f"Suggested artist: {profile.display_name} based on routing rule "
            f"'{highest_rules[0].name}' at priority {highest_priority}. "
            f"Applied routing rules: {rule_names}."
        )
        if support_count:
            reasoning = (
                f"{reasoning} Historical support: {support_count} similar "
                "cases assigned this artist."
            )
        return _ArtistRoutingDecision(
            suggested_artist=profile.display_name,
            confidence_level=confidence,
            reasoning=reasoning,
        )

    def _valid_artist_rules(
        self,
        rules: list[RoutingRule],
        extracted: TattooExtractionDraft,
    ) -> list[RoutingRule]:
        """Keep rules targeting active artists within configured size limits."""
        valid: list[RoutingRule] = []
        size_cm = parse_size_cm(extracted.size_estimate_cm)
        for rule in rules:
            profile = self._artist_config.get_artist_by_key(rule.artist_key)
            if (
                profile is None
                or not self._artist_config.validate_artist_assignment(
                    rule.artist_key,
                    extracted.style_tags,
                )
                or not self._artist_accepts_size(profile, size_cm)
            ):
                LOGGER.warning(
                    "Ignored routing rule %s for unavailable artist %s.",
                    rule.name,
                    rule.artist_key,
                )
                continue
            valid.append(rule)
        return valid

    def _historical_artist_support(
        self,
        artist_key: str,
        matches: list[tuple[float, DecisionHistoryExample]],
    ) -> int:
        """Count unique similar cases supporting one artist assignment."""
        return len(
            {
                example.example_id
                for _, example in matches
                if example.final_artist_key == artist_key
            }
        )

    def _rule_names(self, rules: list[RoutingRule]) -> str:
        """Return a bounded audit label for matching routing rules."""
        names = ", ".join(rule.name for rule in rules[:5])
        if len(rules) > 5:
            names = f"{names}, and {len(rules) - 5} more"
        if len(names) > 220:
            return f"{names[:217]}..."
        return names

    def _suggest_from_config(
        self,
        extracted: TattooExtractionDraft,
    ) -> _ArtistRoutingDecision:
        """Use active artist specialties only when history has no matches."""
        style_tags = set(extracted.style_tags).difference({"unknown"})
        size_cm = parse_size_cm(extracted.size_estimate_cm)
        ranked: list[tuple[int, ArtistProfile]] = []
        for artist in self._artist_config.get_active_artists():
            if not self._artist_accepts_size(artist, size_cm):
                continue
            overlap = style_tags.intersection(artist.specialties)
            if overlap:
                ranked.append((len(overlap), artist))

        if not ranked:
            return _ArtistRoutingDecision(
                suggested_artist="Unclear",
                confidence_level="low",
                reasoning=(
                    "No unique active artist matched configured specialties "
                    "and size limits."
                ),
            )

        best_score = max(score for score, _ in ranked)
        winners = [artist for score, artist in ranked if score == best_score]
        if len(winners) != 1:
            return _ArtistRoutingDecision(
                suggested_artist="Unclear",
                confidence_level="low",
                reasoning=(
                    "Configured specialties produced an unresolved artist tie."
                ),
            )

        winner = winners[0]
        return _ArtistRoutingDecision(
            suggested_artist=winner.display_name,
            confidence_level="medium",
            reasoning=(
                f"Suggested artist: {winner.display_name} based on configured "
                "specialties and size limits."
            ),
        )

    def _artist_accepts_size(
        self,
        artist: ArtistProfile,
        size_cm: Decimal | None,
    ) -> bool:
        """Return whether a known size falls inside an artist's limits."""
        if size_cm is None:
            return True
        if (
            artist.min_size_cm is not None
            and size_cm < Decimal(str(artist.min_size_cm))
        ):
            return False
        if (
            artist.max_size_cm is not None
            and size_cm > Decimal(str(artist.max_size_cm))
        ):
            return False
        return True

    def _classify_risk(
        self,
        extracted: TattooExtractionDraft,
    ) -> RiskLevel:
        """Classify only complete intakes as high risk for staff review."""
        if extracted.conversation_status == "closed":
            return "low"
        return "high" if not extracted.missing_information else "low"

    def _review_reasons(
        self,
        extracted: TattooExtractionDraft,
        artist_decision: _ArtistRoutingDecision,
        current_message: str,
    ) -> list[str]:
        """Identify complexity and immediate staff-review reasons."""
        reasons: list[str] = []
        if specialised_placement_requires_review(extracted.placement):
            reasons.append(SPECIALISED_PLACEMENT_REASON)
        if (
            extracted.client_intent == "status_update"
            or is_status_update_request(current_message)
        ):
            reasons.append(STATUS_UPDATE_REASON)
        if extracted.multi_entity_detected:
            reasons.append("complex_routing_required")
        if extracted.party_size > 1 or len(extracted.projects) > 1:
            reasons.append("multiple_tattoo_projects")
        if extracted.size_description == "not sure":
            reasons.append("client_unsure_about_size")
        if (
            extracted.artist_preference_mode == "recommend"
            and artist_decision.suggested_artist == "Unclear"
        ):
            reasons.append("artist_recommendation_unresolved")
        return reasons

    def _requires_immediate_staff_review(
        self,
        review_reasons: list[str],
    ) -> bool:
        """Return whether intake must pause before ordinary collection.

        Specialised placements keep collecting details and escalate with
        the full intake once it is complete.
        """
        return STATUS_UPDATE_REASON in review_reasons

    def _routing_llm_output(
        self,
        artist_decision: _ArtistRoutingDecision,
        extracted: TattooExtractionDraft,
        risk_level: RiskLevel,
        current_message: str,
        recent_chat_history: list[Message],
    ) -> _RoutingLLMOutput:
        """Generate routing reasoning and the client draft reply."""
        return self._generate_reasoning_and_reply(
            extracted=extracted,
            suggested_artist=artist_decision.suggested_artist,
            risk_level=risk_level,
            current_message=current_message,
            recent_chat_history=recent_chat_history,
        )

    def _combine_routing_reasoning(
        self,
        artist_reasoning: str,
        llm_reasoning: str,
    ) -> str:
        """Keep explicit artist evidence before supplemental risk reasoning."""
        if artist_reasoning.casefold() == llm_reasoning.casefold():
            return artist_reasoning
        return f"{artist_reasoning} {llm_reasoning}"

    def _generate_reasoning_and_reply(
        self,
        extracted: TattooExtractionDraft,
        suggested_artist: SuggestedArtist,
        risk_level: RiskLevel,
        current_message: str,
        recent_chat_history: list[Message],
    ) -> _RoutingLLMOutput:
        """Generate internal reasoning without client-facing prose."""
        try:
            format_instructions = self._parser.get_format_instructions()
            human_prompt = build_routing_human_prompt(
                extracted_data=extracted.model_dump(),
                suggested_artist=suggested_artist,
                risk_level=risk_level,
                current_message=current_message,
                recent_chat_history=recent_chat_history,
                format_instructions=format_instructions,
            )
            response = self._llm.invoke(
                [
                    SystemMessage(content=ROUTING_SYSTEM_PROMPT),
                    HumanMessage(content=human_prompt),
                ]
            )
            parsed = self._parser.parse(self._coerce_content_to_text(response.content))
            return _RoutingLLMOutput.model_validate(parsed)
        except Exception as exc:  # pragma: no cover - defensive branch
            record_llm_failure(exc)
            LOGGER.warning(
                "Routing LLM fallback used: %s [%s]",
                exc,
                llm_failure_context(exc),
            )
            return self._fallback_llm_output(
                suggested_artist=suggested_artist,
                risk_level=risk_level,
            )

    def _fallback_llm_output(
        self,
        suggested_artist: SuggestedArtist,
        risk_level: RiskLevel,
    ) -> _RoutingLLMOutput:
        """Build deterministic output if the LLM call fails."""
        confidence_level: ConfidenceLevel
        if suggested_artist != "Unclear" and risk_level == "low":
            confidence_level = "high"
        elif suggested_artist == "Unclear":
            confidence_level = "low"
        else:
            confidence_level = "medium"

        ai_reasoning = (
            "Applied style and size routing rules, then checked risk keywords "
            "and missing fields for triage."
        )

        return _RoutingLLMOutput(
            confidence_level=confidence_level,
            ai_reasoning=ai_reasoning,
        )

    def _coerce_content_to_text(self, content: Any) -> str:
        """Normalize LangChain content payload to plain text."""
        if isinstance(content, str):
            return content
        if isinstance(content, list):
            text_parts: list[str] = []
            for item in content:
                if isinstance(item, dict):
                    text_value = item.get("text")
                    if isinstance(text_value, str):
                        text_parts.append(text_value)
            return "".join(text_parts)
        return str(content)
